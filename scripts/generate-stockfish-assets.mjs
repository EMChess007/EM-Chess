#!/usr/bin/env node
/**
 * Reads the "lite single-threaded" Stockfish build from node_modules/stockfish/bin
 * (installed via `npm install stockfish`) and emits src/engine/generated/stockfishAssets.ts,
 * a plain TS module exporting the engine's JS source and WASM binary (base64) as string
 * constants, so they can be inlined into the WebView/iframe bridge HTML without relying on
 * runtime asset loading (file:// access, CORS, etc).
 *
 * Re-run this after `npm install stockfish` if you want to switch to a different build
 * (e.g. stockfish-19-lite.js for the multi-threaded variant) or a newer Stockfish version.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');

const jsPath = path.join(projectRoot, 'node_modules/stockfish/bin/stockfish-19-lite-single.js');
const wasmPath = path.join(projectRoot, 'node_modules/stockfish/bin/stockfish-19-lite-single.wasm');
const outPath = path.join(projectRoot, 'src/engine/generated/stockfishAssets.ts');

const jsSource = readFileSync(jsPath, 'utf8');
const wasmBase64 = readFileSync(wasmPath).toString('base64');

const output = `// AUTO-GENERATED by scripts/generate-stockfish-assets.mjs — do not edit by hand.
// Source: stockfish npm package (lite single-threaded build).
// Regenerate with: node scripts/generate-stockfish-assets.mjs

export const STOCKFISH_JS_SOURCE = ${JSON.stringify(jsSource)};

export const STOCKFISH_WASM_BASE64 = ${JSON.stringify(wasmBase64)};
`;

writeFileSync(outPath, output);

console.log(`Wrote ${outPath}`);
console.log(`  JS source: ${(jsSource.length / 1024).toFixed(1)} KB`);
console.log(`  WASM (base64): ${(wasmBase64.length / 1024 / 1024).toFixed(2)} MB`);

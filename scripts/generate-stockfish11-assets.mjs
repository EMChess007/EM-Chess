#!/usr/bin/env node
/**
 * Reads the Stockfish 11 (classical, pre-NNUE evaluation) build from
 * node_modules/stockfish11/src — installed as an aliased devDependency via
 * `npm install --save-dev "stockfish11@npm:stockfish@11.0.0"`, since npm can't install two
 * versions of the same package name side by side otherwise — and emits
 * src/engine/generated/stockfish11Assets.ts, a plain TS module exporting the engine's JS
 * source and WASM binary (base64) as string constants, so they can be inlined into the
 * WebView/iframe bridge HTML without relying on runtime asset loading (file://, CORS, etc).
 *
 * Mirrors scripts/generate-stockfish-assets.mjs (the current/NNUE Stockfish 19 build) — see
 * that script for the general approach. This one targets the last pre-NNUE release instead
 * (Stockfish 12 introduced NNUE), which plays with a distinctly different, more classical
 * positional style and has no large neural-network weights baked in.
 *
 * Re-run this after re-installing the stockfish11 alias if you want to switch pre-NNUE
 * versions.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.join(__dirname, '..');

const jsPath = path.join(projectRoot, 'node_modules/stockfish11/src/stockfish.js');
const wasmPath = path.join(projectRoot, 'node_modules/stockfish11/src/stockfish.wasm');
const outPath = path.join(projectRoot, 'src/engine/generated/stockfish11Assets.ts');

const jsSource = readFileSync(jsPath, 'utf8');
const wasmBase64 = readFileSync(wasmPath).toString('base64');

const output = `// AUTO-GENERATED by scripts/generate-stockfish11-assets.mjs — do not edit by hand.
// Source: stockfish11 npm alias (stockfish@11.0.0, classical pre-NNUE evaluation).
// Regenerate with: node scripts/generate-stockfish11-assets.mjs

export const STOCKFISH11_JS_SOURCE = ${JSON.stringify(jsSource)};

export const STOCKFISH11_WASM_BASE64 = ${JSON.stringify(wasmBase64)};
`;

writeFileSync(outPath, output);

console.log(`Wrote ${outPath}`);
console.log(`  JS source: ${(jsSource.length / 1024).toFixed(1)} KB`);
console.log(`  WASM (base64): ${(wasmBase64.length / 1024 / 1024).toFixed(2)} MB`);

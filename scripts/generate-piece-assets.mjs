/**
 * Writes the BUNDLED piece images of the three built-in image themes (command #27d).
 *
 *   node scripts/generate-piece-assets.mjs            writes assets/pieces/<theme>/<key>.png and src/logic/pieceAssets.ts
 *   node scripts/generate-piece-assets.mjs --check    writes nothing; exits 1 when a file differs from what src/data/pieceSets.json says
 *
 * WHY. The three image themes used to be 36 base64 data URIs that React Native's Image was handed as `{ uri: 'data:image/png;base64,...' }`. A phone showed the black king and queen of Merida
 * in the white pieces' look (Cburnett was right). A data URI is the one image source whose identity is a 5-30 KB string; every layer between the string and the screen (the bridge, the image
 * pipeline's cache key and decoder) can treat it as a key, and none of that can be checked from a browser. A bundled file is an asset id that Metro resolves to a file: nothing is keyed by
 * the bytes. The PIXELS are the same: each file is the base64 payload of src/data/pieceSets.json decoded byte for byte (pieceAssets.test.ts compares them, so the JSON stays the single
 * source the files are made from and the device matrix compares photographs with).
 *
 * Metro needs a literal path in every import, so the registry (src/logic/pieceAssets.ts) is generated, not written by hand.
 */
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import zlib from 'node:zlib';

const appDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');
const THEMES = ['cburnett', 'merida', 'checkers'];
const KEYS = ['wk', 'wq', 'wr', 'wb', 'wn', 'wp', 'bk', 'bq', 'br', 'bb', 'bn', 'bp'];

const sets = JSON.parse(readFileSync(path.join(appDir, 'src', 'data', 'pieceSets.json'), 'utf8'));
let stale = 0;

for (const theme of THEMES) {
  for (const key of KEYS) {
    const uri = sets[theme][key];
    const match = /^data:image\/png;base64,(.+)$/.exec(uri);
    if (!match) throw new Error(`${theme}/${key} is not a PNG data URI`);
    const bytes = Buffer.from(match[1], 'base64');
    const file = path.join(appDir, 'assets', 'pieces', theme, `${key}.png`);
    if (check) {
      if (!existsSync(file) || !readFileSync(file).equals(bytes)) {
        console.error(`stale: ${path.relative(appDir, file)}`);
        stale++;
      }
    } else {
      mkdirSync(path.dirname(file), { recursive: true });
      writeFileSync(file, bytes);
    }
  }
}

// The Piece gallery's probe image: a flat 16 x 16 PNG in the black piece's ink (#1d1d1d), drawn on a light and a dark square next to a plain View and a plain SVG of the same colour. If a phone
// lightens ONE of the three on the dark square, the cause is that kind of drawing and not a piece (src/screens/PieceGalleryScreen.tsx).
function solidPng(size, [r, g, b]) {
  const crcTable = (buffer) => {
    const out = Buffer.alloc(4);
    out.writeUInt32BE(zlib.crc32(buffer) >>> 0);
    return out;
  };
  const chunk = (type, data) => {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, 'latin1'), data]);
    return Buffer.concat([length, body, crcTable(body)]);
  };
  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(size, 0);
  ihdr.writeUInt32BE(size, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  const row = Buffer.concat([Buffer.from([0]), Buffer.from(Array.from({ length: size }, () => [r, g, b, 255]).flat())]);
  const raw = Buffer.concat(Array.from({ length: size }, () => row));
  return Buffer.concat([Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}
const probe = solidPng(16, [0x1d, 0x1d, 0x1d]);
const probeFile = path.join(appDir, 'assets', 'diagnostics', 'probe-black.png');
if (check) {
  if (!existsSync(probeFile) || !readFileSync(probeFile).equals(probe)) {
    console.error('stale: assets/diagnostics/probe-black.png');
    stale++;
  }
} else {
  mkdirSync(path.dirname(probeFile), { recursive: true });
  writeFileSync(probeFile, probe);
}

const lines = [];
lines.push('// GENERATED by scripts/generate-piece-assets.mjs from src/data/pieceSets.json - do not edit by hand (pieceAssets.test.ts compares every file with the JSON).');
lines.push('// The 36 images of the built-in image themes as BUNDLED files: Metro resolves each import to an asset id (command #27d; see the generator for why not data URIs).');
lines.push('');
for (const theme of THEMES) for (const key of KEYS) lines.push(`import ${theme}_${key} from '../../assets/pieces/${theme}/${key}.png';`);
lines.push('');
lines.push("import type { PieceImageMap } from '../types/theme';");
lines.push('');
for (const theme of THEMES) {
  lines.push(`export const ${theme.toUpperCase()}_IMAGES: PieceImageMap = {`);
  for (const key of KEYS) lines.push(`  ${key}: ${theme}_${key},`);
  lines.push('};');
  lines.push('');
}
const registry = lines.join('\n');
const registryFile = path.join(appDir, 'src', 'logic', 'pieceAssets.ts');
if (check) {
  if (!existsSync(registryFile) || readFileSync(registryFile, 'utf8') !== registry) {
    console.error('stale: src/logic/pieceAssets.ts');
    stale++;
  }
  if (stale > 0) process.exit(1);
  console.log('piece assets are in sync with src/data/pieceSets.json');
} else {
  writeFileSync(registryFile, registry);
  console.log(`wrote ${THEMES.length * KEYS.length} PNG files and src/logic/pieceAssets.ts`);
}
